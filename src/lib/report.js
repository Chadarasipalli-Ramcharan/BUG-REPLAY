// Structured bug-report generation (JSON + Markdown) from real DB data.

function fmt(date) {
  return new Date(date).toISOString().replace("T", " ").slice(0, 19) + " UTC";
}

export function buildIssueReport(issue, meta = {}) {
  const { occurrences = [], hints = [], reproduction = [], evidence = [] } = meta;
  return {
    tool: "BugReplay",
    reportType: "bug-investigation-report",
    generatedAt: new Date().toISOString(),
    issue: {
      id: issue.id,
      title: issue.title,
      errorType: issue.errorType,
      message: issue.message,
      fingerprint: issue.fingerprint,
      severity: issue.severity,
      status: issue.status,
      occurrenceCount: issue.occurrenceCount,
      affectedSessionCount: issue.affectedSessionCount,
      firstSeenAt: issue.firstSeenAt,
      lastSeenAt: issue.lastSeenAt,
      latestStackTrace: issue.latestStackTrace,
    },
    summary:
      `"${issue.title}" (${issue.errorType}) was observed ${issue.occurrenceCount} time(s) ` +
      `across ${issue.affectedSessionCount} session(s) between ${fmt(issue.firstSeenAt)} ` +
      `and ${fmt(issue.lastSeenAt)}. Current severity: ${issue.severity}.`,
    reproduction: reproduction.length
      ? reproduction
      : ["No reproduction sequence could be derived from captured events."],
    evidence,
    occurrences: occurrences.map((o) => ({
      at: o.occurredAt,
      sessionId: o.sessionId,
      pageUrl: o.session?.pageUrl ?? null,
      environment: o.session?.environment ?? null,
      event: o.event
        ? { type: o.event.type, name: o.event.name, selector: o.event.selector }
        : null,
    })),
    diagnostics: {
      note:
        "Hypotheses only — rule-based suggestions tied to captured evidence. " +
        "None of these is a confirmed root cause.",
      hints,
    },
    limitations: [
      "Event-based capture only; this is not pixel-perfect visual playback.",
      "Severity labels are transparent triage heuristics, not business-impact assessments.",
      "Privacy: form values, credentials, and request/response bodies are never captured.",
    ],
  };
}

export function reportToMarkdown(report) {
  const i = report.issue;
  const L = [];
  L.push(`# Bug Report — ${i.title}`);
  L.push("");
  L.push(`_Generated by BugReplay on ${report.generatedAt}_`);
  L.push("");
  L.push("## Summary");
  L.push("");
  L.push(report.summary);
  L.push("");
  L.push("## Error details");
  L.push("");
  L.push("| Field | Value |");
  L.push("| --- | --- |");
  L.push(`| Issue ID | \`${i.id}\` |`);
  L.push(`| Fingerprint | \`${i.fingerprint}\` |`);
  L.push(`| Error type | ${i.errorType} |`);
  L.push(`| Severity | ${i.severity} |`);
  L.push(`| Status | ${i.status} |`);
  L.push(`| Occurrences | ${i.occurrenceCount} |`);
  L.push(`| Affected sessions | ${i.affectedSessionCount} |`);
  L.push(`| First seen | ${fmt(i.firstSeenAt)} |`);
  L.push(`| Last seen | ${fmt(i.lastSeenAt)} |`);
  L.push("");
  L.push(`**Message:** ${i.message}`);
  L.push("");
  if (i.latestStackTrace) {
    L.push("**Stack trace (most recent capture):**");
    L.push("");
    L.push("```");
    L.push(i.latestStackTrace);
    L.push("```");
    L.push("");
  }
  L.push("## Reproduction steps (derived from captured events)");
  L.push("");
  report.reproduction.forEach((step, n) => L.push(`${n + 1}. ${step}`));
  L.push("");
  L.push("## Evidence");
  L.push("");
  if (!report.evidence.length) {
    L.push("_No supporting evidence events were captured._");
  } else {
    for (const e of report.evidence) {
      L.push(
        `- **${fmt(e.at)}** — ${e.type}${e.name ? `: ${e.name}` : ""} ` +
          `(_session ${String(e.sessionId).slice(0, 8)}…${
            e.pageUrl ? `, ${e.pageUrl}` : ""
          }_)`
      );
      if (e.detail) L.push(`  - ${e.detail}`);
    }
  }
  L.push("");
  L.push("## Occurrence history");
  L.push("");
  L.push("| When (UTC) | Session | Page | Triggering event |");
  L.push("| --- | --- | --- | --- |");
  for (const o of report.occurrences) {
    L.push(
      `| ${fmt(o.at)} | ${String(o.sessionId).slice(0, 8)}… | ${o.pageUrl ?? "-"} | ${
        o.event ? `${o.event.type}${o.event.name ? `: ${o.event.name}` : ""}` : "-"
      } |`
    );
  }
  L.push("");
  L.push("## Diagnostic suggestions");
  L.push("");
  L.push(`> ${report.diagnostics.note}`);
  L.push("");
  for (const h of report.diagnostics.hints) {
    L.push(`### ${h.label}`);
    L.push("");
    L.push(h.suggestion);
    L.push("");
    L.push(`Evidence: ${h.evidence}`);
    L.push("");
  }
  L.push("## Limitations");
  L.push("");
  report.limitations.forEach((l) => L.push(`- ${l}`));
  L.push("");
  L.push("---");
  L.push("_BugReplay — the time machine for software bugs._");
  return L.join("\n");
}
